defmodule OhMyJidoDocsWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :oh_my_jido_docs

  @session_options [
    store: :cookie,
    key: "_oh_my_jido_docs_key",
    signing_salt: "zjh6CpbM",
    same_site: "Lax",
    http_only: true,
    secure: Application.compile_env(:oh_my_jido_docs, :secure_session_cookie, true),
    max_age: 8 * 60 * 60
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :oh_my_jido_docs,
    gzip: not code_reloading?,
    only: OhMyJidoDocsWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library()

  plug :remember_original_method
  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug OhMyJidoDocsWeb.Router

  defp remember_original_method(%{method: "HEAD"} = conn, _options) do
    Plug.Conn.put_private(conn, :docs_original_method, "HEAD")
  end

  defp remember_original_method(conn, _options), do: conn
end

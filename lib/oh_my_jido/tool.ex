defmodule OhMyJido.Tool do
  @moduledoc """
  Authorizes tool effects and executes registered Jido Actions.

  Prefer `OhMyJido.execute_tool/4` for a managed session. Use this module when
  trusted integration code already has an `OhMyJido.Context`.

  Built-in Actions check their permission with `authorize/3` at the point of
  the effect. Custom Actions without `capability/0` require `:custom`.
  Declaring `capability/0` alone does not authorize an effect: the Action must
  call `authorize/3` or a library operation that does.

  `execute/4` records effects when the context has a session coordinator.
  A standalone context has no managed journal or approval conversation.
  An approval request in that context returns `{:error, :approval_required}`.
  Effect consent accepts only `true`, `:approve`, or `"approve"`.

  A call through a session may run for `tool_timeout_ms` plus
  `question_timeout_ms`, so waiting for an approval or answer does not use up
  the tool budget. The allowance covers one wait; a call that asks more than
  once, such as a Git commit, shares it. A question whose waiting call ends is
  withdrawn. Commands the call starts still stop at `tool_timeout_ms`.

  Effects are never automatically retried. If execution finishes but recording
  fails, the returned uncertain result must be reconciled rather than replayed.
  """

  alias OhMyJido.{Context, Host, Persistence}

  @doc "Authorizes an effect and, when needed, waits for a structured human answer."
  @spec authorize(map() | Context.t(), atom(), map()) :: :ok | {:error, term()}
  def authorize(execution_context, capability, effect \\ %{}) do
    with {:ok, context} <- Context.fetch(execution_context),
         true <- Context.permitted?(context, capability) do
      case Host.call(context, :authorize, [capability, effect]) do
        :ok ->
          :ok

        {:error, reason} when is_atom(reason) ->
          {:error, reason}

        {:error, {reason, detail}} when is_atom(reason) and is_atom(detail) ->
          {:error, {reason, detail}}

        {:error, _reason} ->
          {:error, {:host_denied, capability}}

        {:approval, question} when is_map(question) ->
          approve(context, question)

        _invalid ->
          {:error, :authorization_service_failed}
      end
    else
      false -> {:error, {:permission_denied, capability}}
      {:error, _reason} = error -> error
    end
  rescue
    _error -> {:error, :authorization_service_failed}
  catch
    _kind, _reason -> {:error, :authorization_service_failed}
  end

  @doc "Finds a tool by its exact registered name without creating atoms."
  @spec find(Context.t(), String.t()) :: {:ok, module()} | {:error, term()}
  def find(%Context{tools: tools}, name) when is_binary(name) do
    case Enum.find(tools, &(&1.name() == name)) do
      nil -> {:error, {:unknown_tool, name}}
      action -> {:ok, action}
    end
  end

  @doc """
  Executes a registered tool through Jido.Exec with no effect retries.

  The default `:timeout` is the call limit from `call_timeout/1`. An explicit
  `:timeout` replaces it for this call, including approval waits inside the
  Action. The `:custom` approval for an Action without `capability/0` is asked
  before the call starts and is limited by `question_timeout_ms` instead.

  Host callers may supply an `:effect_id` to correlate the durable receipt.
  Reusing a recorded ID rejects the call before execution; this option is not
  accepted from model-facing tool parameters. IDs are generated by default.

  If post-execution bookkeeping fails, the error includes the entire sanitized
  native result under `:result`, the `:effect_id`, and the bookkeeping `:cause`.
  Its `:reason` is `:effect_recording_failed` and its `:effect` is `:uncertain`;
  callers must reconcile the receipt instead of retrying the operation.
  """
  @spec execute(map() | Context.t(), String.t(), map(), [
          {:timeout, non_neg_integer()} | {:effect_id, String.t()}
        ]) :: term()
  def execute(execution_context, name, params, opts \\ []) do
    with {:ok, context} <- Context.fetch(execution_context),
         {:ok, action} <- find(context, name),
         :ok <- authorize_custom(context, action, params),
         {:ok, secrets} <- redaction_secrets(context),
         call = %{
           id: Keyword.get_lazy(opts, :effect_id, &Jido.Util.generate_id/0),
           name: name,
           action_module: action,
           arguments: params
         },
         :ok <- begin_effect(context, call) do
      result =
        Jido.Exec.run(action, params, %{oh_my_jido: context},
          timeout: Keyword.get_lazy(opts, :timeout, fn -> call_timeout(context) end),
          max_retries: 0
        )

      complete_effect(context, call.id, result, secrets)
    end
  end

  @doc """
  Returns how long one tool call may run in milliseconds.

  With a session coordinator this is `tool_timeout_ms` plus
  `question_timeout_ms`, so one approval or answer can wait its full question
  limit; a call that asks more than once shares that allowance. A standalone
  context cannot wait for answers and uses `tool_timeout_ms`. Missing limits
  default to 30,000 and 300,000.
  """
  @spec call_timeout(Context.t()) :: non_neg_integer()
  def call_timeout(%Context{coordinator: nil, limits: limits}),
    do: Map.get(limits, :tool_timeout_ms, 30_000)

  def call_timeout(%Context{limits: limits}),
    do: Map.get(limits, :tool_timeout_ms, 30_000) + Map.get(limits, :question_timeout_ms, 300_000)

  @doc false
  @spec authorize_custom(Context.t(), module(), map()) :: :ok | {:error, term()}
  def authorize_custom(context, action, params) do
    if function_exported?(action, :capability, 0) do
      :ok
    else
      authorize(context, :custom, %{tool: action.name(), parameters: params})
    end
  end

  defp complete_effect(context, id, result, secrets) do
    case redact_result(context, result) do
      {:ok, safe_result} ->
        case finish_effect(context, id, safe_result) do
          :ok -> safe_result
          {:error, reason} -> recording_error(id, safe_result, reason, secrets)
        end

      {:error, reason} ->
        recording_error(id, Persistence.clean(result, secrets), reason, secrets)
    end
  end

  defp recording_error(id, result, reason, secrets) do
    {:error,
     %{
       reason: :effect_recording_failed,
       cause: Persistence.clean(reason, secrets),
       effect: :uncertain,
       effect_id: Persistence.clean(id, secrets),
       result: result
     }}
  end

  defp redaction_secrets(%Context{coordinator: nil}), do: {:ok, []}

  defp redaction_secrets(context),
    do: OhMyJido.Session.redaction_secrets(context.coordinator)

  defp begin_effect(%Context{coordinator: nil}, _call), do: :ok

  defp begin_effect(context, call),
    do: OhMyJido.Session.effect_started(context.coordinator, context.run_id, call)

  defp finish_effect(%Context{coordinator: nil}, _id, _result), do: :ok

  defp finish_effect(context, id, result),
    do: OhMyJido.Session.effect_finished(context.coordinator, context.run_id, id, result)

  defp redact_result(%Context{coordinator: nil}, result), do: {:ok, result}

  defp redact_result(context, result),
    do: OhMyJido.Session.redact_result(context.coordinator, result)

  defp approve(%Context{coordinator: nil}, _question), do: {:error, :approval_required}

  defp approve(context, question) do
    case OhMyJido.Session.question(context.coordinator, question) do
      {:ok, answer} when answer in [true, :approve, "approve"] -> :ok
      {:ok, _answer} -> {:error, :approval_denied}
      {:error, _reason} = error -> error
    end
  end
end
